from sortedcontainers.sortedset import SortedSet

if __name__ == "__main__":
    # --- 基本操作 ---
    x = SortedSet(range(1000000))
    assert x[0] == 0
    # 差集合で範囲を一括削除
    x.difference_update(range(10000))
    assert x[0] == 10000

    # --- 挿入と削除 ---
    s = SortedSet([3, 1, 4, 1, 5])
    # 重複は自動で除外される: [1, 3, 4, 5]
    assert list(s) == [1, 3, 4, 5]
    s.add(2)  # 2を追加 -> [1, 2, 3, 4, 5]
    s.discard(3)  # 3を削除 -> [1, 2, 4, 5]
    assert 3 not in s

    # --- インデックスアクセス (k番目の値) ---
    assert s[0] == 1   # 最小値
    assert s[-1] == 5  # 最大値
    assert s[2] == 4   # 3番目に小さい値

    # --- 二分探索 ---
    # bisect_left: 指定以上の最小インデックス
    assert s.bisect_left(4) == 2
    # bisect_right: 指定を超える最小インデックス
    assert s.bisect_right(4) == 3

    # --- 範囲クエリ (irange) ---
    # 2 <= val <= 5 の範囲を取り出す
    assert list(s.irange(2, 5)) == [2, 4, 5]
