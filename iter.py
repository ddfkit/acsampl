import itertools

# https://github.com/ddfkit/acsampl/blob/main/iter.py
# Generated by Gemini prior to contest (AtCoder Rule 20251003 compliant)
def rle(s):
    return [(k,len(list(g))) for k,g in itertools.groupby(s)]

# https://github.com/ddfkit/acsampl/blob/main/iter.py
# Generated by Gemini prior to contest (AtCoder Rule 20251003 compliant)
def rle_decode(runs):
    return "".join(k*cnt for k,cnt in runs)

if __name__ == "__main__":
    res = rle("aaabbcccca")
    assert res == [('a', 3), ('b', 2), ('c', 4), ('a', 1)]
    assert rle_decode(res) == "aaabbcccca"

    p = list(itertools.permutations(range(3), 2))
    assert len(p) == 6
    c = list(itertools.combinations(range(4), 2))
    assert len(c) == 6
    prod = list(itertools.product([0, 1], repeat=3))
    assert len(prod) == 8
    print("iter.py: tests passed!")
